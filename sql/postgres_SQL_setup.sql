ALTER DATABASE postgres SET timezone TO 'America/Sao_Paulo';

-------------------------
-- TABLES
-------------------------

CREATE TABLE pharmacy (
    id SERIAL PRIMARY KEY,
    code_pharmacy VARCHAR(20) UNIQUE NOT NULL,
    trade_name VARCHAR(255) NOT NULL,
    category VARCHAR(20) NOT NULL,
    corporate_name VARCHAR(255),
    address VARCHAR(500) DEFAULT 'não informado',
    nit VARCHAR(20),
    lat DECIMAL(10, 6),
    lon DECIMAL(10, 6),
    enabled BOOLEAN DEFAULT false,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_modified TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pharmacy_code ON pharmacy(code_pharmacy);
CREATE INDEX idx_pharmacy_category ON pharmacy(category);
CREATE INDEX idx_pharmacy_enabled ON pharmacy(enabled);

create table public.file_logs (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default (now() AT TIME ZONE 'America/Sao_Paulo'::text),
  aws_filename text null,
  original_path text null,
  file_modified_at timestamp without time zone null,
  shell_output text null,
  md5_checksum text null,
  execution_id text null,
  executed_at timestamp without time zone null,
  status integer null,
  constraint file_logs_pkey primary key (id)
) TABLESPACE pg_default;

